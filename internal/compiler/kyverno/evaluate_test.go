// A file with no document holds no resource. The CLI loads it without complaint, so a tree of such files
// passes. A document that is not a Kubernetes object fails the load instead.
func TestEvaluateAnEmptyManifestHoldsNoResource(t *testing.T) {
	requireEngine(t)
	root := t.TempDir()
	writeTree(t, root, map[string]string{"empty/a.yaml": "", "empty/b.yaml": "# nothing here\n", "values/v.yaml": "replicas: 2\n"})
	if out := evaluateReal(realEnv(t, root, "empty"), "block", golden(t, "example-10")); out.Err != nil || len(out.Violations) != 0 {
		t.Fatalf("empty files: %+v", out)
	}
	out := evaluateReal(realEnv(t, root, "values"), "block", golden(t, "example-10"))
	requireOutcomeCode(t, out, CodeRun)
	if !strings.Contains(out.Err.Error(), "failed to load resources") {
		t.Fatalf("err %v", out.Err)
	}
}

func TestEvaluateWaiverCoversFindingsAndNotErrors(t *testing.T) {
	requireEngine(t)
	bad := t.TempDir()
	writeTree(t, bad, map[string]string{"k8s/bad.yaml": pod("bad", "", false)})
	entry := entryFor("block")
	entry.Waivers = []compiler.ManifestWaiver{{Approver: "Ada Lovelace", ValidFrom: "2026-01-01", ValidTo: "2026-03-01"}}
	env := realEnv(t, bad, "k8s")
	out := env.Evaluate(context.Background(), entry, golden(t, "example-10"), evalNow)
	if out.Err != nil || !out.Waived || len(out.Violations) != 1 {
		t.Fatalf("waived: %+v", out)
	}

	// The expression reads a key the pod does not have, which Kyverno reports as an error result.
	policy := customPolicy(t, "    - expression: object.spec.securityContext.runAsNonRoot == true\n      message: x\n")
	out = env.Evaluate(context.Background(), entry, map[string][]byte{artifactName: policy}, evalNow)
	requireCode(t, out.Err, CodeIncomplete)
	if out.Waived || len(out.Violations) != 0 {
		t.Fatalf("an error was waived: %+v", out)
	}
}

// Both of these stop the CLI before it prints a report. Neither may become a pass.
func TestEvaluateLoadFailuresAreErrors(t *testing.T) {
	requireEngine(t)
	cases := map[string]map[string]string{
		"broken yaml":                  {"k8s/api.yaml": "kind: [\n"},
		"a document with no kind":      {"k8s/api.yaml": "foo: bar\n"},
		"two files name one resource":  {"k8s/a.yaml": pod("api", "", true), "k8s/b.yaml": pod("api", "", true)},
		"a good pod and a broken file": {"k8s/a.yaml": pod("api", "", true), "k8s/b.yaml": "kind: [\n"},
	}
	for name, files := range cases {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			writeTree(t, root, files)
			out := evaluateReal(realEnv(t, root, "k8s"), "block", golden(t, "example-10"))
			requireOutcomeCode(t, out, CodeRun)
		})
	}
	// The panic of the pinned release names the duplicated resource. A later release that fixes the panic
	// and reports both resources changes this contract together with the pin.
	root := t.TempDir()
	writeTree(t, root, map[string]string{"k8s/a.yaml": pod("api", "", true), "k8s/b.yaml": pod("api", "", true)})
	out := evaluateReal(realEnv(t, root, "k8s"), "block", golden(t, "example-10"))
	if !strings.Contains(out.Err.Error(), "status 2: panic: pods") {
		t.Fatalf("err %v", out.Err)
	}
}

// Compile parses CEL and does not type-check it. The CLI type-checks the policy before it matches a
// resource, so an expression that cannot run is an error even when no loaded resource is a pod.
func TestEvaluateAPolicyTheCLIRefusesIsAnError(t *testing.T) {
	requireEngine(t)
	policy := customPolicy(t, "    - expression: 1 + 'a' == 2\n      message: x\n")
	for name, manifest := range map[string]string{"a pod": pod("api", "", true), "a config map": configMap} {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			writeTree(t, root, map[string]string{"k8s/a.yaml": manifest})
			out := evaluateReal(realEnv(t, root, "k8s"), "block", map[string][]byte{artifactName: policy})
			requireOutcomeCode(t, out, CodeRun)
			if !strings.Contains(out.Err.Error(), "failed to apply policies") {
				t.Fatalf("err %v", out.Err)
			}
		})
	}
}

// image(ref) parses a reference string and needs no registry, so compile keeps it and the run passes on a
// registry name that cannot be resolved. image.GetMetadata is the call that reads image data, and compile
// rejects it (ADR-0037).
func TestEvaluateImageFunctionOnlyParsesAReference(t *testing.T) {
	requireEngine(t)
	root := t.TempDir()
	manifest := strings.Replace(pod("api", "", true), "example.invalid/a:1", "registry.invalid/team/api:1", 1)
	writeTree(t, root, map[string]string{"k8s/a.yaml": manifest})
	policy := customPolicy(t, "    - expression: image(object.spec.containers[0].image).registry() == 'registry.invalid'\n      message: x\n")
	started := time.Now()
	out := evaluateReal(realEnv(t, root, "k8s"), "block", map[string][]byte{artifactName: policy})
	if out.Err != nil || len(out.Violations) != 0 || out.Waived {
		t.Fatalf("outcome %+v", out)
	}
	if time.Since(started) > time.Minute {
		t.Fatal("the run waited on a registry")
	}
	src := "apiVersion: policies.kyverno.io/v1\nkind: ValidatingPolicy\nmetadata:\n  name: custom\nspec:\n  matchConstraints:\n    resourceRules:\n      - apiGroups: [\"\"]\n        apiVersions: [v1]\n        operations: [CREATE]\n        resources: [pods]\n  validations:\n    - expression: image.GetMetadata('registry.invalid/team/api:1').config.architecture == 'amd64'\n      message: x\n"
	_, err := compilePolicy([]byte(src), "block")
	requireCode(t, err, CodeCEL)
}

