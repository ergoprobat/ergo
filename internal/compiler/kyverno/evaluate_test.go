// The tests below run the pinned Kyverno CLI. They need IPSO_KYVERNO=1 and kyverno 1.19.2 on PATH,
// installed with testdata/tool/install.sh.

func requireEngine(t *testing.T) {
	t.Helper()
	if os.Getenv("IPSO_KYVERNO") == "" {
		t.Skip("IPSO_KYVERNO is not set")
	}
	if _, err := exec.LookPath("kyverno"); err != nil {
		t.Fatal("kyverno is not on PATH")
	}
}

func entryFor(mode string) compiler.Entry {
	return compiler.Entry{
		DecisionID:      "01M5WVYECH20GSNT3MW1VM5CC5",
		Slug:            "pods",
		Engine:          "kyverno",
		Mode:            mode,
		CompilerVersion: version,
		ValidFrom:       "2026-01-01",
	}
}

var evalNow = time.Date(2026, 2, 1, 12, 0, 0, 0, time.UTC)

func requireOutcomeCode(t *testing.T, out compiler.Outcome, code string) {
	t.Helper()
	requireCode(t, out.Err, code)
	if len(out.Violations) != 0 || out.Waived {
		t.Fatalf("outcome %+v", out)
	}
}

func realEnv(t *testing.T, root string, named ...string) *Env {
	t.Helper()
	requireEngine(t)
	env, err := Setup(context.Background(), root, named)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(env.Close)
	return env
}

func pod(name, namespace string, nonRoot bool) string {
	text := "apiVersion: v1\nkind: Pod\nmetadata:\n  name: " + name + "\n"
	if namespace != "" {
		text += "  namespace: " + namespace + "\n"
	}
	text += "spec:\n"
	if nonRoot {
		text += "  securityContext:\n    runAsNonRoot: true\n"
	}
	return text + "  containers:\n    - name: a\n      image: example.invalid/a:1\n"
}

const deployment = `apiVersion: apps/v1
kind: Deployment
metadata:
  name: dep
spec:
  selector:
    matchLabels:
      app: dep
  template:
    metadata:
      labels:
        app: dep
    spec:
      containers:
        - name: a
          image: example.invalid/a:1
`

const configMap = "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: cm\n"

// customPolicy compiles a ValidatingPolicy over pods with the given validations, the way ipso compile does.
func customPolicy(t *testing.T, validations string) []byte {
	t.Helper()
	src := `apiVersion: policies.kyverno.io/v1
kind: ValidatingPolicy
metadata:
  name: custom
spec:
  matchConstraints:
    resourceRules:
      - apiGroups: [""]
        apiVersions: [v1]
        operations: [CREATE, UPDATE]
        resources: [pods]
  validations:
` + validations
	out, err := compilePolicy([]byte(src), "block")
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func golden(t *testing.T, name string) map[string][]byte {
	t.Helper()
	return map[string][]byte{artifactName: []byte(readGolden(t, name))}
}

func evaluateReal(env *Env, mode string, artifacts map[string][]byte) compiler.Outcome {
	return env.Evaluate(context.Background(), entryFor(mode), artifacts, evalNow)
}

func TestEvaluateCleanAndViolating(t *testing.T) {
	requireEngine(t)
	clean := t.TempDir()
	writeTree(t, clean, map[string]string{"k8s/good.yaml": pod("good", "", true)})
	if out := evaluateReal(realEnv(t, clean, "k8s"), "block", golden(t, "example-10")); out.Err != nil || len(out.Violations) != 0 || out.Waived {
		t.Fatalf("clean: %+v", out)
	}

	bad := t.TempDir()
	writeTree(t, bad, map[string]string{"k8s/bad.yaml": pod("bad", "team-a", false)})
	out := evaluateReal(realEnv(t, bad, "k8s"), "block", golden(t, "example-10"))
	if out.Err != nil || out.Waived || len(out.Violations) != 1 {
		t.Fatalf("violating: %+v", out)
	}
	if got := out.Violations[0]; got.Address != "team-a/Pod/bad" || got.Message != "runAsNonRoot must be true" {
		t.Fatalf("violation %+v", got)
	}
}

// Deny, Warn, and Audit all report fail and exit 1. The mode decides the exit status of ipso, not the CLI's.
